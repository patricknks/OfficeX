export function tr(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.lang) ?? 'en';
  return (key: Key, vars?: Record<string, string | number>) => tr(lang, key, vars);
}

export function agoText(lang: Lang, ts: number | string): string {
  const t = typeof ts === 'string' ? Date.parse(ts) : ts;
  const s = Math.max(0, Math.round((Date.now() - t) / 1000));
  if (s < 45) return tr(lang, 'ago.now');
  const m = Math.round(s / 60);
  if (m < 60) return tr(lang, 'ago.min', { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return tr(lang, 'ago.hour', { n: h });
  const d = Math.round(h / 24);
  return d === 1 ? tr(lang, 'ago.yesterday') : tr(lang, 'ago.days', { n: d });
}
